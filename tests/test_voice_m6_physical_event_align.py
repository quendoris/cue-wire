"""M6 physical event/audio alignment test: only synthetic anonymized markers.

No real audio, event devices, key identity, keyboard readers or playback.
"""
from __future__ import annotations

import math
from pathlib import Path
import sys
import unittest
from unittest.mock import patch

import numpy as np

sys.path.insert(0,str(Path(__file__).resolve().parents[1]/"tools"))
import voice_m6_physical_event_align as sync


def synthetic_alignment(with_impulses: bool = True):
    """14-second fabricated signal, known offsets, separate holdout."""
    base=1_000_000_000_000
    seconds=14
    phases=[
        ("quiet_baseline",0,1),
        ("mouse_isolated",1,3.6),
        ("keyboard_isolated",3.6,6.2),
        ("both_holdout",6.2,12.8),
        ("voice_only_holdout",12.8,13.4),
        ("voice_clicks_holdout",13.4,14),
    ]
    manifest={
        # Mirror the real capture metadata contract expected by align().
        # The hashes here are synthetic placeholders; file integrity
        # belongs to the separate read_capture() entry-point gate.
        "schema":"cuewire-M6-physical-anonymous-events-v1",
        "capture_files_sha256":{
            "microphone.wav":"0"*64,
            "anonymous-events.jsonl":"1"*64,
        },
        "session_start_monotonic_ns":base,
        "phases":[{
            "phase":name,
            "start_monotonic_ns":base+round(a*1e9),
            "end_monotonic_ns":base+round(b*1e9),
        } for name,a,b in phases],
    }
    feature=np.zeros(seconds*1000,dtype=np.float64)
    rng=np.random.default_rng(5161)
    # Independent baseline transients (not generated by event markers).
    feature[:]=rng.uniform(0.,.06,len(feature))
    offsets={
        "mouse_press":19,
        "mouse_release":17,
        "keyboard_press":24,
        "keyboard_release":10,
    }
    times={}
    for name in sync.KINDS:
        if name.startswith("mouse"):
            train=np.arange(1.2,3.34,.19)
        else:
            train=np.arange(3.8,6.01,.17)
        if name.endswith("release"):
            train=train+.075
        held=np.arange(6.45,12.31,.47)
        held += rng.uniform(-.048,.048,len(held))
        if name.endswith("release"):
            held=held+.075
        times[name]=(train,held)
    events=[]
    for kind,(training,heldout) in times.items():
        for seconds_at in np.concatenate((training,heldout)):
            stamp=base+round(float(seconds_at)*1e9)
            events.append({"kind":kind,"t_monotonic_ns":stamp})
            if with_impulses:
                at=round(seconds_at*1000)-offsets[kind]
                for d in range(-3,4):
                    feature[at+d] += 4*math.exp(-.5*(d/1.4)**2)
    events.sort(key=lambda e:e["t_monotonic_ns"])
    return manifest,np.zeros(seconds*sync.RATE),events,feature,offsets


class PhysicalEventAlignmentTests(unittest.TestCase):
    def test_missing_source_metadata_fails_explicitly(self):
        manifest,mic,events,feature,_=synthetic_alignment()
        del manifest["schema"]
        with patch.object(sync,"transient_feature",return_value=feature):
            with self.assertRaisesRegex(ValueError,"schema"):
                sync.align(manifest,mic,events,n_perm=100)

    def test_heldout_recovers_exact_class_effective_offsets(self):
        manifest,mic,events,feature,offsets=synthetic_alignment()
        with patch.object(sync,"transient_feature",return_value=feature):
            result=sync.align(manifest,mic,events,n_perm=250)
        self.assertTrue(result["acceptance"])
        self.assertFalse(result[
            "mic_sample_zero_monotonic_ns_separately_identified"])
        self.assertFalse(result["mechanical_click_cancellation_performed"])
        for kind in sync.KINDS:
            row=result["class_results"][kind]
            self.assertLessEqual(
                abs(row["effective_acoustic_offset_ms"]-offsets[kind]),5)
            self.assertTrue(row["passed_independent_holdout"])
            self.assertGreater(row["heldout_transient_score"],
                               row["heldout_circular_null_p95"])

    def test_nothing_correlated_does_not_pass_validation(self):
        manifest,mic,events,feature,_=synthetic_alignment(
            with_impulses=False)
        with patch.object(sync,"transient_feature",return_value=feature):
            result=sync.align(manifest,mic,events,n_perm=200)
        self.assertFalse(result["acceptance"])

    def test_event_scores_reject_empty_or_outside_pcm(self):
        signal=np.zeros(1000,dtype=np.float64)
        with self.assertRaisesRegex(ValueError,"No event"):
            sync.score_times(signal,np.array([]),20)
        with self.assertRaisesRegex(ValueError,"outside"):
            sync.score_times(signal,np.array([4000.]),20)
        with self.assertRaisesRegex(ValueError,"Unsupported permutation"):
            manifest,mic,events,feature,_=synthetic_alignment()
            with patch.object(sync,"transient_feature",return_value=feature):
                sync.align(manifest,mic,events,n_perm=2)


if __name__=="__main__":
    unittest.main()
