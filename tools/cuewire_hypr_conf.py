#!/usr/bin/env python3
"""CueWire M7.4: safe legacy hyprland.conf integration for Hyprland < 0.55.

This does NOT guess the user's Hyprland version or overwrite their config.
A read-only preview shows the exact include line and diff. --apply
requires an explicit existing config path, active Hyprland 0.54 or older,
verified current keybinds, a private backup, and a valid local keymap.
The existing user config is left untouched except for one clearly marked
include block. There is NO automatic compositor reload.

Hyprland 0.55+ uses Lua and DOES NOT support this legacy .conf pathway.
Do not attempt to add source= or old bind syntax to a new Lua config.
"""
from __future__ import annotations

import argparse
import difflib
import os
from pathlib import Path
import re
import stat
import subprocess
import sys
import tempfile
from datetime import datetime, timezone

import cuewire_hotkeys
import cuewire_keymap as keymap

START="# >>> CueWire M7.4 managed include (user-approved) >>>"
END="# <<< CueWire M7.4 managed include <<<"
INCLUDED=keymap.DIRECTORY/"cuewire-keymap-v1.conf"
MAX_CONFIG=2_000_000
VERSION_RE=re.compile(r"\bHyprland\s+v?(\d+)\.(\d+)(?:\.(\d+))?",re.I)
SAFE_CONF_RE=re.compile(r"/[A-Za-z0-9_./-]+\Z")


class ConfError(RuntimeError):
    pass


def version_from_text(value:str)->tuple[int,int,int]:
    match=VERSION_RE.search(value)
    if not match:
        # Hyprland sometimes prints "Hyprland, built from branch..." with
        # a "Tag: v0.54.0" line rather than a version on the first line.
        match=re.search(r"(?im)^\s*Tag:\s*v?(\d+)\.(\d+)(?:\.(\d+))?",value)
    if not match:
        raise ConfError("Cannot determine Hyprland version; refuse to edit config")
    return tuple(int(group or "0") for group in match.groups())


def require_legacy_hyprland()->tuple[int,int,int]:
    try:
        finished=subprocess.run(
            ["hyprctl","version"],
            capture_output=True,text=True,stdin=subprocess.DEVNULL,
            timeout=3,check=False,
        )
    except (OSError,subprocess.TimeoutExpired) as exc:
        raise ConfError("hyprctl version unavailable; no changes made") from exc
    if finished.returncode:
        raise ConfError("Cannot query active Hyprland version; no changes made")
    version=version_from_text(finished.stdout)
    if version >= (0,55,0):
        raise ConfError(
            "Hyprland 0.55+ requires Lua, not hyprland.conf. "
            "Do not apply legacy binds; migrate config separately."
        )
    return version


def current_config_path(config:str|None)->Path:
    if config is not None:
        path=Path(config).expanduser()
    else:
        base=Path(os.environ.get("XDG_CONFIG_HOME",str(Path.home()/".config")))
        path=base/"hypr"/"hyprland.conf"
    if not path.is_absolute():
        raise ConfError("Config path must be absolute")
    # Don't rewrite symlinks: the actual destination might not be the
    # config Hyprland uses, or may be outside the user's home directory.
    if path.is_symlink():
        raise ConfError("Refusing symlinked config; supply real config path")
    try:
        metadata=path.lstat()
    except OSError as exc:
        raise ConfError("Active .conf path missing/unreadable; supply --config") from exc
    if (path.suffix!=".conf" or not stat.S_ISREG(metadata.st_mode)
            or metadata.st_uid!=os.getuid()
            or metadata.st_size>MAX_CONFIG):
        raise ConfError("Refuse non-regular/foreign/oversized Hyprland .conf")
    return path


def render_conf(mapping:dict[str,str])->str:
    """Render the OFFICIAL pre-0.55 hyprlang bind flags only.

    bind[ip]d: ignore held modifiers / bypass game input inhibition /
    has description. Chords use bindpd without ignore-mods; panic is
    fixed SUPER+C. Never bind on lockscreen, capture real keys or
    expand user text into an exec command.
    """
    safe=keymap.validate(mapping)
    executable=keymap.ROOT/"target/release/cuewire"
    emergency=keymap.ROOT/"tools/cuewire_scope.sh"
    for path in (executable,emergency,INCLUDED):
        if not SAFE_CONF_RE.fullmatch(str(path)):
            raise ConfError("Unsafe path for hyprlang config")
    lines=[
        "# Generated by CueWire M7.4: do NOT edit manually.",
        "# Legacy Hyprland .conf (pre-0.55) ONLY; this is NOT Lua.",
        "# No autostart; existing system audio defaults remain untouched.",
        "# Descriptions allow read-only verification via hyprctl -j binds.",
        "# User map SHA256: "+keymap.digest(mapping),
    ]
    for action in keymap.ACTIONS:
        combo=safe.get(action)
        if combo is None:
            continue
        fields=combo.split(" + ")
        mods=" ".join(fields[:-1])
        keysym=fields[-1]
        flag=("bindipd" if not mods and keysym in keymap.KEYS
              else "bindpd")
        control=("stop" if action=="stop" else
                 "toggle "+action.split(":")[1])
        lines.append(
            f"{flag} = {mods}, {keysym}, CueWire M7.4 {action}, "
            f"exec, {executable} ctl {control}"
        )
    lines.append(
        "bindpd = SUPER, C, CueWire M7.4 emergency, "
        f"exec, /usr/bin/bash {emergency} emergency"
    )
    return "\n".join(lines)+"\n"


def include_block()->str:
    if not SAFE_CONF_RE.fullmatch(str(INCLUDED)):
        raise ConfError("Unsafe generated .conf include path")
    return f"{START}\nsource = {INCLUDED}\n{END}"


def merged_config(original:str)->str:
    """Fail closed on double includes or user edits inside owned block."""
    if "\x00" in original or "\r" in original:
        raise ConfError("Nonstandard or binary line endings; no changes")
    block=include_block()
    if START in original or END in original:
        # Only replace the EXACT previously generated block, not
        # arbitrary user text with a matching marker.
        rx=re.compile(
            re.escape(START)+r"\nsource = "+
            re.escape(str(INCLUDED))+r"\n"+re.escape(END)
        )
        if original.count(START)!=1 or original.count(END)!=1:
            raise ConfError("Ambiguous CueWire managed blocks")
        if len(rx.findall(original))!=1:
            raise ConfError("CueWire managed block was edited; refuse overwrite")
        return rx.sub(block,original,count=1)
    if re.search(
        r"(?m)^\s*source\s*=\s*"+re.escape(str(INCLUDED))+r"\s*$",
        original,
    ):
        raise ConfError("CueWire source already included outside managed block")
    return original.rstrip("\n")+"\n\n"+block+"\n"


def read_current(path:Path)->tuple[str,bytes,int]:
    data=path.read_bytes()
    if len(data)>MAX_CONFIG:
        raise ConfError("Config grew beyond safety limit")
    try:
        text=data.decode("utf-8")
    except UnicodeError as exc:
        raise ConfError("Config is not valid UTF-8") from exc
    return text,data,path.stat().st_mode&0o777


def private_write(target:Path,text:str,mode:int=0o600)->None:
    if target.is_symlink():
        raise ConfError("Refusing symlink destination")
    if target.exists():
        meta=target.lstat()
        if not stat.S_ISREG(meta.st_mode) or meta.st_uid!=os.getuid():
            raise ConfError("Refusing non-regular/foreign destination")
    fd,name=tempfile.mkstemp(prefix=".cuewire-conf-",dir=target.parent)
    try:
        os.fchmod(fd,mode)
        with os.fdopen(fd,"w",encoding="utf-8") as out:
            out.write(text)
            out.flush()
            os.fsync(out.fileno())
        os.replace(name,target)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def backup_original(path:Path,data:bytes)->Path:
    """Create a UNIQUE owner-only backup beside the active .conf."""
    stamp=datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    base=path.with_name(path.name+".cuewire-"+stamp)
    for i in range(100):
        copy=base.with_name(base.name+f"-{i:02}.bak")
        try:fd=os.open(copy,os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600)
        except FileExistsError:continue
        try:
            with os.fdopen(fd,"wb") as out:
                out.write(data)
                out.flush()
                os.fsync(out.fileno())
        except BaseException:
            copy.unlink(missing_ok=True)
            raise
        return copy
    raise ConfError("Cannot allocate unique private config backup")


def foreign_conflicts(mapping:dict[str,str])->list[str]:
    try:
        live=cuewire_hotkeys.load_hyprctl()
    except (RuntimeError,ValueError,OSError) as exc:
        raise ConfError("Cannot inspect current Hyprland binds") from exc
    if not isinstance(live,list):
        raise ConfError("Bad hyprctl binds response")
    return keymap.conflicts(mapping,live)


def run(argv:list[str]|None=None)->int:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "action",choices=("inspect","preview","apply"),
        help="inspect/preview never write; apply explicitly updates .conf",
    )
    parser.add_argument(
        "--config",help="EXACT real active hyprland.conf (otherwise XDG default)",
    )
    parsed=parser.parse_args(argv)
    try:
        version=require_legacy_hyprland()
        file=current_config_path(parsed.config)
        existing,raw,mode=read_current(file)
        mapping=keymap.read_profile()
        material=render_conf(mapping)
        merged=merged_config(existing)
        print(f"Hyprland: {'.'.join(map(str,version))} (legacy .conf supported)")
        print("Existing config:",file)
        print("Generated cue bindings:",INCLUDED)
        print("No device defaults, config or compositor settings changed yet.")
        if parsed.action=="inspect":
            issues=foreign_conflicts(mapping)
            if issues:
                print("REFUSED foreign bind conflicts:\n"+"\n".join(issues))
                return 2
            print("PASS: no foreign conflicting Hyprland keys reported")
            return 0
        if parsed.action=="preview":
            print("Generated CueWire .conf:\n"+material)
            print("Main config diff:")
            print("".join(difflib.unified_diff(
                existing.splitlines(keepends=True),
                merged.splitlines(keepends=True),
                fromfile=str(file),tofile=str(file)+" (proposed)",
            )))
            print("PREVIEW ONLY — no files written")
            return 0
        issues=foreign_conflicts(mapping)
        if issues:
            raise ConfError("Foreign Hyprland bindings conflict:\n"+
                            "\n".join(issues))
        keymap.private_directory()
        keymap.DIRECTORY.mkdir(mode=0o700,exist_ok=True)
        # Read again before the actual write: fail on intervening edit.
        if file.read_bytes()!=raw:
            raise ConfError("Hyprland config changed during preflight")
        backup=backup_original(file,raw)
        # Write generated file first, so the source always points to
        # valid existing content when the main config is updated.
        private_write(INCLUDED,material)
        try:
            private_write(file,merged,mode)
        except BaseException:
            # Main config wasn't successfully replaced; backup remains.
            raise
        print("Backup:",backup)
        print("Updated ONLY one CueWire source block in:",file)
        print("NO hyprctl reload invoked; apply manually after review.")
        print("Run: hyprctl reload")
        print("Then: python3 tools/cuewire_keymap.py verify")
        return 0
    except (ConfError,keymap.KeymapError,OSError) as exc:
        print("REFUSED:",str(exc),file=sys.stderr)
        return 2


if __name__=="__main__":
    raise SystemExit(run())
